# ── недоопределённые фразы: каталог команд (intent-catalog.ts) ──────────────
# expect.tier: execute (молча + earcon) | confirm («Сделать …?») | clarify (вопрос) | llm.
# expect.action — что исполняется; expect.question — точный вопрос.
def addx(tier, domain, items):
    kind = {"execute": "cmd", "confirm": "clarify", "clarify": "clarify", "llm": "llm", "reprompt": "reprompt"}[tier]
    for item in items:
        text, action, question = (item + (None, None))[:3] if isinstance(item, tuple) else (item, None, None)
        r = {"text": text, "expect": {"kind": kind, "domain": domain, "tier": tier}}
        if action: r["expect"]["action"] = action
        if question: r["expect"]["question"] = question
        rows.append(r)

